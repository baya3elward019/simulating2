"""IDS workbook: Inputs → Detection Results → Bayes Calculation → Scenario Comparison.

All expected values are live formulas built on named Inputs cells (TotalPackets, MaliciousRate,
DetectionRate, FalsePositiveRate). Monte Carlo results, when present, are written as static amber
values (they are one random sample) next to live "Simulated − Expected" formulas.
"""
from __future__ import annotations

from typing import Any

from openpyxl import Workbook
from openpyxl.chart import BarChart, Reference
from openpyxl.worksheet.datavalidation import DataValidation

from ... import xlsx_style as st
from .engine import simulate

INPUTS, DETECT, BAYES, COMPARE = "Inputs", "Detection Results", "Bayes Calculation", "Scenario Comparison"
NUM, PCT = "#,##0.00", "0.00%"
TRUE_COLOR, FALSE_COLOR, PPV_COLOR = "2FBF9F", "FF6B6B", "6687FF"


def build_workbook(params: dict[str, Any] | None = None) -> Workbook:
    result = simulate(params)
    wb = Workbook()
    _inputs(wb, wb.active, result)
    _detection(wb.create_sheet(DETECT), result)
    _bayes(wb.create_sheet(BAYES))
    _comparison(wb.create_sheet(COMPARE), result)
    st.finish(wb)
    return wb


def _inputs(wb: Workbook, ws, result: dict[str, Any]) -> None:
    p = result["inputs"]
    ws.title = INPUTS
    st.title(ws, "IDS Detection & Bayes – Inputs  |  مدخلات نظام كشف التسلل",
             "Blue cells are editable (rates are percentages). Every other sheet recalculates from them.")
    st.header(ws, 4, ["Parameter / المتغير", "Value / القيمة", "Excel name", "Meaning / المعنى"])
    rows = [
        ("Total packets / إجمالي الحزم", p["packets"], "TotalPackets", "#,##0", "Number of packets inspected by the IDS."),
        ("Malicious traffic rate / نسبة الحزم الخبيثة", p["malicious_pct"] / 100, "MaliciousRate", PCT, "Prior P(M): share of packets that are really malicious."),
        ("Detection rate (TPR) / معدل الكشف", p["tpr_pct"] / 100, "DetectionRate", PCT, "P(Alarm | Malicious): sensitivity of the IDS."),
        ("False positive rate (FPR) / الإنذار الكاذب", p["fpr_pct"] / 100, "FalsePositiveRate", PCT, "P(Alarm | Benign): benign packets wrongly flagged."),
    ]
    for i, (label, value, name, fmt, meaning) in enumerate(rows):
        r = 5 + i
        st.cell(ws, r, 1, label, bold=True)
        st.cell(ws, r, 2, value, fmt=fmt, fill=st.INPUT_FILL)
        st.cell(ws, r, 3, name, mono=True)
        st.cell(ws, r, 4, meaning)
        st.define(wb, name, INPUTS, f"$B${r}")
    sim = result["simulated"]
    st.header(ws, 10, ["Monte Carlo run / تجربة مونت كارلو", "Value", "", ""])
    st.cell(ws, 11, 1, "Included in this file?", bold=True)
    st.cell(ws, 11, 2, "Yes" if sim else "No", fill=st.STATIC_FILL)
    st.cell(ws, 12, 1, "Random seed", bold=True)
    st.cell(ws, 12, 2, p["seed"] if sim else "—", fill=st.STATIC_FILL)
    st.note(ws, 13, 1, "Monte Carlo counts are one random sample generated by Python; they are static. Expected values are live formulas.")
    st.header(ws, 15, ["Check / تحقق", "Result", "", "Formula"])
    check = '=IF(AND(TotalPackets>=1,MaliciousRate>=0,MaliciousRate<=1,DetectionRate>=0,DetectionRate<=1,FalsePositiveRate>=0,FalsePositiveRate<=1),"OK ✓","Error: packets ≥ 1 and rates in 0%–100%")'
    st.cell(ws, 16, 1, "Inputs valid?", bold=True)
    st.cell(ws, 16, 2, check)
    st.cell(ws, 16, 4, check[1:], mono=True)

    packets = DataValidation(type="whole", operator="greaterThanOrEqual", formula1="1", showErrorMessage=True,
                             errorTitle="Invalid packets", error="Total packets must be a whole number ≥ 1.")
    rate = DataValidation(type="decimal", operator="between", formula1="0", formula2="1", showErrorMessage=True,
                          errorTitle="Invalid rate", error="Rates must be between 0% and 100%.")
    ws.add_data_validation(packets); ws.add_data_validation(rate)
    packets.add("B5"); rate.add("B6:B8")
    st.widths(ws, {"A": 44, "B": 16, "C": 20, "D": 62})
    ws.freeze_panes = "A5"


DETECT_ROWS = [  # (label, law, formula) — rows 5…13
    ("Malicious packets", "N × m", "=TotalPackets*MaliciousRate", "malicious"),
    ("Benign packets", "N × (1 − m)", "=TotalPackets*(1-MaliciousRate)", "benign"),
    ("True positives (TP)", "Malicious × TPR", "=C5*DetectionRate", "tp"),
    ("False negatives (FN)", "Malicious × (1 − TPR)", "=C5*(1-DetectionRate)", "fn"),
    ("False positives (FP)", "Benign × FPR", "=C6*FalsePositiveRate", "fp"),
    ("True negatives (TN)", "Benign × (1 − FPR)", "=C6*(1-FalsePositiveRate)", "tn"),
    ("Total alerts", "TP + FP", "=C7+C9", "alerts"),
    ("Check: TP + FN + FP + TN", "must equal N", "=C7+C8+C9+C10", "packets"),
    ("P(Malicious | Alarm)", "TP / (TP + FP)", '=IF(C11=0,"N/A – no alarms",C7/C11)', "p_malicious_given_alarm"),
]


def _detection(ws, result: dict[str, Any]) -> None:
    sim = result["simulated"]
    st.title(ws, "Detection Results  |  نتائج الكشف",
             "Expected = live Excel formulas. Simulated = one Monte Carlo sample (static, amber) when it was run in SimuLab.")
    st.header(ws, 4, ["Quantity / الكمية", "Law", "Expected (formula)", "Simulated (Monte Carlo)", "Simulated − Expected"])
    for i, (label, law, formula, key) in enumerate(DETECT_ROWS):
        r = 5 + i
        fmt = PCT if key == "p_malicious_given_alarm" else NUM
        st.cell(ws, r, 1, label, bold=True)
        st.cell(ws, r, 2, law)
        st.cell(ws, r, 3, formula, fmt=fmt, fill=st.CALC_FILL)
        value = sim.get(key) if sim else None
        st.cell(ws, r, 4, value if value is not None else "—", fmt=fmt if value is not None else None, fill=st.STATIC_FILL)
        st.cell(ws, r, 5, f'=IF(AND(ISNUMBER(C{r}),ISNUMBER(D{r})),D{r}-C{r},"—")', fmt=fmt)

    st.header(ws, 4, ["Confusion matrix", "Alarm (predicted malicious)", "No alarm (predicted benign)", "Total"], col=7)
    matrix = [("Actually malicious", "=C7", "=C8", "=H5+I5"), ("Actually benign", "=C9", "=C10", "=H6+I6"),
              ("Total", "=H5+H6", "=I5+I6", "=J5+J6")]
    for i, (label, a, b, total) in enumerate(matrix):
        r = 5 + i
        st.cell(ws, r, 7, label, bold=True)
        st.cell(ws, r, 8, a, fmt=NUM, fill=st.PatternFill("solid", fgColor="FFDDF6EF" if i == 0 else "FFFFE3E3") if i < 2 else None)
        st.cell(ws, r, 9, b, fmt=NUM, fill=st.PatternFill("solid", fgColor="FFFFE3E3" if i == 0 else "FFDDF6EF") if i < 2 else None)
        st.cell(ws, r, 10, total, fmt=NUM, bold=i == 2)
    st.note(ws, 8, 7, "Green = correct decisions (TP, TN). Red = errors (FN missed attack, FP false alarm).")

    st.header(ws, 10, ["Metric / المؤشر", "Value", "Formula", ""], col=7)
    metrics = [
        ("Precision = P(Malicious | Alarm)", '=IF(H7=0,"N/A – no alarms",H5/H7)'),
        ("P(False alarm | Alarm)", '=IF(H7=0,"N/A – no alarms",H6/H7)'),
        ("Recall (TPR)", "=DetectionRate"),
        ("Specificity (1 − FPR)", "=1-FalsePositiveRate"),
        ("P(Benign | No alarm) – NPV", '=IF(I7=0,"N/A",I6/I7)'),
        ("Accuracy (TP + TN) / N", "=(H5+I6)/J7"),
        ("F1 score 2TP / (2TP + FP + FN)", '=IF(2*H5+H6+I5=0,"N/A",2*H5/(2*H5+H6+I5))'),
    ]
    for i, (label, formula) in enumerate(metrics):
        r = 11 + i
        st.cell(ws, r, 7, label, bold=True)
        st.cell(ws, r, 8, formula, fmt=PCT)
        st.cell(ws, r, 9, formula[1:], mono=True)

    if sim:
        top = 20
        ws.cell(row=top, column=1, value=f"Monte Carlo packet log – first {len(sim['sample'])} of {sim['packets']:,} packets (seed “{sim['seed']}”)").font = st.Font(bold=True, size=12)
        st.header(ws, top + 1, ["Packet", "U₁ (class)", "Malicious? (U₁ < m)", "U₂ (alarm)", "Alarm? (U₂ < TPR or FPR)", "Outcome"])
        for i, s in enumerate(sim["sample"]):
            r = top + 2 + i
            st.cell(ws, r, 1, s["packet"])
            st.cell(ws, r, 2, s["u_class"], fmt="0.0000", fill=st.STATIC_FILL)
            st.cell(ws, r, 3, "Yes" if s["malicious"] else "No")
            st.cell(ws, r, 4, s["u_alarm"], fmt="0.0000", fill=st.STATIC_FILL)
            st.cell(ws, r, 5, "Yes" if s["alarm"] else "No")
            st.cell(ws, r, 6, s["outcome"], bold=True)
    st.widths(ws, {"A": 26, "B": 22, "C": 20, "D": 24, "E": 22, "F": 10, "G": 34, "H": 24, "I": 44, "J": 14})


def _bayes(ws) -> None:
    st.title(ws, "Bayes Calculation  |  حساب قانون بايز",
             "P(M|A) = P(A|M)·P(M) / [P(A|M)·P(M) + P(A|B)·P(B)] — every step is a live formula.")
    st.header(ws, 4, ["Step / الخطوة", "Probability", "Value", "Formula", "Meaning / المعنى"])
    steps = [
        ("1. Prior", "P(M)", "=MaliciousRate", "Chance that a random packet is malicious."),
        ("2. Complement", "P(B) = 1 − P(M)", "=1-C5", "Chance that a packet is benign."),
        ("3. Likelihood", "P(A | M) = TPR", "=DetectionRate", "Alarm probability for a malicious packet."),
        ("4. False-alarm likelihood", "P(A | B) = FPR", "=FalsePositiveRate", "Alarm probability for a benign packet."),
        ("5. Joint", "P(A ∩ M) = P(A|M)·P(M)", "=C7*C5", "Alarm AND malicious (true alerts share)."),
        ("6. Joint", "P(A ∩ B) = P(A|B)·P(B)", "=C8*C6", "Alarm AND benign (false alerts share)."),
        ("7. Total probability", "P(A) = P(A∩M) + P(A∩B)", "=C9+C10", "Overall chance of an alarm."),
        ("8. Posterior (Bayes)", "P(M | A) = P(A∩M) / P(A)", '=IF(C11=0,"N/A – no alarms",C9/C11)', "Chance that an alarm is real."),
        ("9. Posterior complement", "P(B | A) = P(A∩B) / P(A)", '=IF(C11=0,"N/A – no alarms",C10/C11)', "Chance that an alarm is false."),
        ("Cross-check with counts", "TP / (TP + FP)", f"='{DETECT}'!C13", "Same answer from the Detection Results sheet."),
        ("Difference", "Bayes − counts", '=IF(AND(ISNUMBER(C12),ISNUMBER(C14)),C12-C14,"—")', "≈ 0: the two methods agree."),
    ]
    for i, (label, prob, formula, meaning) in enumerate(steps):
        r = 5 + i
        st.cell(ws, r, 1, label, bold=True)
        st.cell(ws, r, 2, prob)
        st.cell(ws, r, 3, formula, fmt="0.00E+00" if label == "Difference" else "0.0000%", fill=st.CALC_FILL)
        st.cell(ws, r, 4, formula[1:], mono=True)
        st.cell(ws, r, 5, meaning)
    ws["A18"] = "With your numbers:"
    ws["A18"].font = st.Font(bold=True)
    ws["B18"] = ('="P(M|A) = "&TEXT(C7,"0.00%")&" × "&TEXT(C5,"0.00%")&" / ("&TEXT(C7,"0.00%")&" × "&TEXT(C5,"0.00%")'
                 '&" + "&TEXT(C8,"0.00%")&" × "&TEXT(C6,"0.00%")&") = "&TEXT(C9,"0.0000")&" / "&TEXT(C11,"0.0000")'
                 '&" = "&IF(ISNUMBER(C12),TEXT(C12,"0.00%"),"N/A (no alarms)")')
    ws["B18"].font = st.Font(name="Consolas", size=11, bold=True)
    st.note(ws, 19, 1, "Base-rate effect: when malicious traffic is rare, even a 99% detector produces mostly false alarms.")
    st.widths(ws, {"A": 26, "B": 30, "C": 16, "D": 40, "E": 48})


COMPARE_HEAD = ["Scenario", "Total packets", "Malicious rate", "Detection rate (TPR)", "False positive rate", "Malicious", "Benign",
                "True alerts (TP)", "False alerts (FP)", "FN", "TN", "Total alerts", "P(Malicious | Alarm)", "P(False alarm | Alarm)"]


def _comparison(ws, result: dict[str, Any]) -> None:
    st.title(ws, "Scenario Comparison  |  مقارنة السيناريوهات",
             "Row 5 follows the Inputs sheet. Other rows have their own blue inputs. Copy the last row down to add a scenario.")
    st.header(ws, 4, COMPARE_HEAD)
    scenarios = result["comparison"]
    for i, s in enumerate(scenarios):
        r = 5 + i
        inp = s["inputs"]
        if i == 0:
            st.cell(ws, r, 1, "Current (Inputs sheet)", bold=True)
            for col, formula, fmt in ((2, "=TotalPackets", "#,##0"), (3, "=MaliciousRate", PCT), (4, "=DetectionRate", PCT), (5, "=FalsePositiveRate", PCT)):
                st.cell(ws, r, col, formula, fmt=fmt)
        else:
            st.cell(ws, r, 1, s["name"], bold=True, fill=st.INPUT_FILL)
            st.cell(ws, r, 2, inp["packets"], fmt="#,##0", fill=st.INPUT_FILL)
            for col, key in ((3, "malicious_pct"), (4, "tpr_pct"), (5, "fpr_pct")):
                st.cell(ws, r, col, inp[key] / 100, fmt=PCT, fill=st.INPUT_FILL)
        formulas = [f"=B{r}*C{r}", f"=B{r}*(1-C{r})", f"=F{r}*D{r}", f"=G{r}*E{r}", f"=F{r}*(1-D{r})", f"=G{r}*(1-E{r})",
                    f"=H{r}+I{r}", f'=IF(L{r}=0,"N/A",H{r}/L{r})', f'=IF(L{r}=0,"N/A",I{r}/L{r})']
        for j, formula in enumerate(formulas):
            st.cell(ws, r, 6 + j, formula, fmt=PCT if j >= 7 else NUM, fill=st.CALC_FILL)
    last = 4 + len(scenarios)
    st.note(ws, last + 2, 1, "Formulas (row 5): Malicious =B5*C5 · TP =F5*D5 · FP =G5*E5 · P(M|A) =IF(L5=0,\"N/A\",H5/L5)")

    names = Reference(ws, min_col=1, min_row=5, max_row=last)
    bars = BarChart()
    bars.type = "col"
    bars.grouping = "clustered"
    bars.title = "True alerts vs false alerts"
    bars.y_axis.title = "Packets"
    bars.add_data(Reference(ws, min_col=8, max_col=9, min_row=4, max_row=last), titles_from_data=True)
    bars.set_categories(names)
    for s, color in zip(bars.series, (TRUE_COLOR, FALSE_COLOR)):
        s.graphicalProperties.solidFill = color
        s.graphicalProperties.line.solidFill = color
    bars.height, bars.width = 9, 17
    bars.x_axis.delete = False
    bars.y_axis.delete = False
    ws.add_chart(bars, f"A{last + 4}")

    ppv = BarChart()
    ppv.type = "col"
    ppv.title = "P(Malicious | Alarm) per scenario"
    ppv.add_data(Reference(ws, min_col=13, min_row=4, max_row=last), titles_from_data=True)
    ppv.set_categories(names)
    ppv.series[0].graphicalProperties.solidFill = PPV_COLOR
    ppv.y_axis.number_format = "0%"
    ppv.y_axis.scaling.min = 0
    ppv.y_axis.scaling.max = 1
    ppv.height, ppv.width = 9, 13
    ppv.x_axis.delete = False
    ppv.y_axis.delete = False
    ws.add_chart(ppv, f"H{last + 4}")
    st.widths(ws, {"A": 30, **{c: 15 for c in "BCDEFGHIJKL"}, "M": 20, "N": 20})
    ws.freeze_panes = "B5"
